BEGIN;

UPDATE motions SET committee = NULL WHERE committee IS NOT NULL AND length(trim(committee)) = 0;

ALTER TABLE motions
  ADD COLUMN motion_number BIGINT GENERATED BY DEFAULT AS IDENTITY,
  ADD COLUMN public_title TEXT,
  ADD COLUMN public_summary TEXT,
  ADD COLUMN reviewed_by UUID REFERENCES users(id) ON DELETE RESTRICT,
  ADD COLUMN reviewed_at TIMESTAMPTZ,
  ADD COLUMN review_reason_code TEXT;

ALTER TABLE motions
  ADD CONSTRAINT motions_number_unique UNIQUE (motion_number),
  ADD CONSTRAINT motions_public_title_check
    CHECK (public_title IS NULL OR length(trim(public_title)) BETWEEN 5 AND 160),
  ADD CONSTRAINT motions_public_summary_check
    CHECK (public_summary IS NULL OR length(trim(public_summary)) BETWEEN 20 AND 1200),
  ADD CONSTRAINT motions_public_fields_pair_check
    CHECK ((public_title IS NULL) = (public_summary IS NULL)),
  ADD CONSTRAINT motions_review_fields_pair_check
    CHECK ((reviewed_by IS NULL) = (reviewed_at IS NULL)),
  ADD CONSTRAINT motions_review_reason_check
    CHECK (review_reason_code IS NULL OR review_reason_code IN (
      'out_of_scope', 'duplicate', 'insufficient_detail', 'procedural'
    )),
  ADD CONSTRAINT motions_committee_length_check
    CHECK (committee IS NULL OR length(trim(committee)) BETWEEN 2 AND 120);

UPDATE motions
SET submitted_at = created_at
WHERE status <> 'draft' AND submitted_at IS NULL;

CREATE INDEX motions_proposer_history_idx ON motions(proposed_by, created_at DESC);
CREATE INDEX motions_review_queue_idx ON motions(status, submitted_at ASC)
  WHERE status = 'submitted';

CREATE TABLE motion_lifecycle_events (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  motion_id UUID NOT NULL REFERENCES motions(id) ON DELETE RESTRICT,
  actor_user_id UUID NOT NULL REFERENCES users(id) ON DELETE RESTRICT,
  event_type TEXT NOT NULL CHECK (event_type IN ('baseline', 'submitted', 'reviewed')),
  from_status motion_status,
  to_status motion_status NOT NULL,
  request_id TEXT CHECK (request_id IS NULL OR length(request_id) <= 128),
  metadata JSONB NOT NULL DEFAULT '{}'::jsonb CHECK (jsonb_typeof(metadata) = 'object'),
  created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
  CHECK (
    (event_type IN ('baseline', 'submitted') AND from_status IS NULL)
    OR (event_type = 'reviewed' AND from_status IS NOT NULL)
  )
);
CREATE INDEX motion_lifecycle_history_idx
  ON motion_lifecycle_events(motion_id, created_at DESC);

INSERT INTO motion_lifecycle_events
  (motion_id, actor_user_id, event_type, from_status, to_status, metadata, created_at)
SELECT id, proposed_by, 'baseline', NULL, status, '{"backfilled":true}'::jsonb, created_at
FROM motions;

CREATE FUNCTION reject_motion_lifecycle_event_mutation()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
BEGIN
  RAISE EXCEPTION 'motion_lifecycle_events are append-only';
END;
$$;
CREATE TRIGGER motion_lifecycle_events_no_update_delete
BEFORE UPDATE OR DELETE ON motion_lifecycle_events
FOR EACH ROW EXECUTE FUNCTION reject_motion_lifecycle_event_mutation();

CREATE FUNCTION enforce_motion_write()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  actor_setting TEXT;
  actor_id UUID;
  actor_role TEXT;
  actor_status TEXT;
  consent_id UUID;
  sitting_state TEXT;
BEGIN
  actor_setting := nullif(current_setting('app.actor_user_id', true), '');
  IF actor_setting IS NULL THEN
    RAISE EXCEPTION 'authenticated delegate or clerk context is required';
  END IF;
  actor_id := actor_setting::uuid;

  SELECT role::text, status::text INTO actor_role, actor_status
  FROM users WHERE id = actor_id FOR SHARE;
  IF actor_status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION 'active Assembly account required';
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.proposed_by IS DISTINCT FROM actor_id
      OR NEW.status <> 'submitted'
      OR NEW.submitted_at IS NULL
      OR NEW.reviewed_by IS NOT NULL
      OR NEW.reviewed_at IS NOT NULL
      OR NEW.public_title IS NOT NULL
      OR NEW.public_summary IS NOT NULL
      OR NEW.review_reason_code IS NOT NULL
      OR NEW.committee IS NOT NULL
    THEN
      RAISE EXCEPTION 'new motions must be submitted by their authenticated delegate';
    END IF;
    IF actor_role IS DISTINCT FROM 'delegate' THEN
      RAISE EXCEPTION 'only an active delegate may submit a motion';
    END IF;

    SELECT id INTO consent_id
    FROM guardian_consents
    WHERE child_user_id = actor_id
      AND status = 'approved'
      AND withdrawn_at IS NULL
    ORDER BY created_at DESC
    LIMIT 1
    FOR SHARE;
    IF consent_id IS NULL THEN
      RAISE EXCEPTION 'approved guardian consent is required to submit a motion';
    END IF;

    SELECT status::text INTO sitting_state
    FROM sittings WHERE id = NEW.sitting_id FOR SHARE;
    IF sitting_state NOT IN ('published', 'in_progress') THEN
      RAISE EXCEPTION 'motions may only be submitted to an open published sitting';
    END IF;
    RETURN NEW;
  END IF;

  IF NEW.id IS DISTINCT FROM OLD.id
    OR NEW.motion_number IS DISTINCT FROM OLD.motion_number
    OR NEW.sitting_id IS DISTINCT FROM OLD.sitting_id
    OR NEW.proposed_by IS DISTINCT FROM OLD.proposed_by
    OR NEW.title IS DISTINCT FROM OLD.title
    OR NEW.description IS DISTINCT FROM OLD.description
    OR NEW.submitted_at IS DISTINCT FROM OLD.submitted_at
    OR NEW.created_at IS DISTINCT FROM OLD.created_at
  THEN
    RAISE EXCEPTION 'submitted motion identity and original text are immutable';
  END IF;

  IF actor_role NOT IN ('clerk', 'admin') THEN
    RAISE EXCEPTION 'active clerk or administrator required to review a motion';
  END IF;
  IF OLD.status <> 'submitted'
    OR NEW.status NOT IN ('under_debate', 'committee_review', 'rejected')
    OR NEW.reviewed_by IS DISTINCT FROM actor_id
    OR NEW.reviewed_at IS NULL
    OR NEW.reviewed_at IS NOT DISTINCT FROM OLD.reviewed_at
  THEN
    RAISE EXCEPTION 'motion is not eligible for this review transition';
  END IF;

  IF NEW.status IN ('under_debate', 'committee_review') THEN
    IF NEW.public_title IS NULL OR NEW.public_summary IS NULL
      OR NEW.review_reason_code IS NOT NULL
    THEN
      RAISE EXCEPTION 'accepted motion requires reviewed public wording';
    END IF;
    IF NEW.status = 'committee_review' AND NEW.committee IS NULL THEN
      RAISE EXCEPTION 'committee referral requires a committee';
    END IF;
    SELECT status::text INTO sitting_state
    FROM sittings WHERE id = NEW.sitting_id FOR SHARE;
    IF sitting_state NOT IN ('published', 'in_progress') THEN
      RAISE EXCEPTION 'motion cannot be advanced after its sitting closes';
    END IF;
  ELSE
    IF NEW.public_title IS NOT NULL OR NEW.public_summary IS NOT NULL
      OR NEW.review_reason_code IS NULL
      OR NEW.committee IS NOT NULL
    THEN
      RAISE EXCEPTION 'rejected motion requires a reason code and no public wording';
    END IF;
  END IF;
  RETURN NEW;
END;
$$;

CREATE TRIGGER motions_write_scope
BEFORE INSERT OR UPDATE ON motions
FOR EACH ROW EXECUTE FUNCTION enforce_motion_write();

CREATE FUNCTION enforce_motion_event_insert()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  actor_setting TEXT;
  actor_role TEXT;
  actor_status TEXT;
  motion_status_value TEXT;
  proposer UUID;
BEGIN
  IF NEW.event_type = 'baseline' THEN RETURN NEW; END IF;
  actor_setting := nullif(current_setting('app.actor_user_id', true), '');
  IF actor_setting IS NULL OR NEW.actor_user_id::text <> actor_setting THEN
    RAISE EXCEPTION 'motion event actor does not match authenticated context';
  END IF;

  SELECT role::text, status::text INTO actor_role, actor_status
  FROM users WHERE id = NEW.actor_user_id FOR SHARE;
  IF actor_status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION 'active account required for motion event';
  END IF;

  SELECT status::text, proposed_by INTO motion_status_value, proposer
  FROM motions WHERE id = NEW.motion_id;
  IF motion_status_value IS DISTINCT FROM NEW.to_status::text THEN
    RAISE EXCEPTION 'motion event does not match current status';
  END IF;

  IF NEW.event_type = 'submitted' THEN
    IF actor_role IS DISTINCT FROM 'delegate'
      OR proposer IS DISTINCT FROM NEW.actor_user_id
      OR NEW.from_status IS NOT NULL
      OR NEW.to_status <> 'submitted'
    THEN
      RAISE EXCEPTION 'invalid motion submission event';
    END IF;
  ELSIF NEW.event_type = 'reviewed' THEN
    IF actor_role NOT IN ('clerk', 'admin')
      OR NEW.from_status <> 'submitted'
      OR NEW.to_status NOT IN ('under_debate', 'committee_review', 'rejected')
    THEN
      RAISE EXCEPTION 'invalid motion review event';
    END IF;
  ELSE
    RAISE EXCEPTION 'unsupported motion lifecycle event';
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER motion_lifecycle_events_authenticated_insert
BEFORE INSERT ON motion_lifecycle_events
FOR EACH ROW EXECUTE FUNCTION enforce_motion_event_insert();

CREATE FUNCTION require_motion_lifecycle_and_audit()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
  actor_setting TEXT;
  actor_id UUID;
  expected_event TEXT;
  expected_action TEXT;
  expected_from motion_status;
BEGIN
  actor_setting := nullif(current_setting('app.actor_user_id', true), '');
  IF actor_setting IS NULL THEN RAISE EXCEPTION 'motion write is missing actor context'; END IF;
  actor_id := actor_setting::uuid;

  IF TG_OP = 'INSERT' THEN
    expected_event := 'submitted';
    expected_action := 'motion.submitted';
    expected_from := NULL;
  ELSE
    expected_event := 'reviewed';
    expected_action := 'motion.reviewed';
    expected_from := OLD.status;
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM motion_lifecycle_events e
    WHERE e.motion_id = NEW.id
      AND e.actor_user_id = actor_id
      AND e.event_type = expected_event
      AND e.from_status IS NOT DISTINCT FROM expected_from
      AND e.to_status = NEW.status
  ) THEN
    RAISE EXCEPTION 'motion write requires a matching append-only lifecycle event';
  END IF;

  IF NOT EXISTS (
    SELECT 1 FROM audit_logs a
    WHERE a.actor_user_id = actor_id
      AND a.entity_type = 'motion'
      AND a.entity_id = NEW.id
      AND a.action = expected_action
  ) THEN
    RAISE EXCEPTION 'motion write requires a matching audit record';
  END IF;
  RETURN NEW;
END;
$$;
CREATE CONSTRAINT TRIGGER motions_lifecycle_audit_guard
AFTER INSERT OR UPDATE ON motions
DEFERRABLE INITIALLY DEFERRED
FOR EACH ROW EXECUTE FUNCTION require_motion_lifecycle_and_audit();

CREATE VIEW public_motion_summary WITH (security_barrier = true) AS
SELECT id, motion_number, sitting_id, public_title AS title,
       public_summary AS summary, committee, status, submitted_at, reviewed_at
FROM motions
WHERE status IN ('under_debate', 'committee_review', 'adopted')
  AND reviewed_by IS NOT NULL
  AND public_title IS NOT NULL
  AND public_summary IS NOT NULL;

COMMIT;
